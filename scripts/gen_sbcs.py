"""Writes runtime/sbcs_tables.go: the single-byte codecs of CPython (code pages,
ISO 8859, KOI8, Mac) as 256-entry tables, with their aliases."""
import codecs
import json
import encodings.aliases as al

names = ["cp437", "cp737", "cp775", "cp850", "cp852", "cp855", "cp857", "cp858", "cp860", "cp861", "cp862", "cp863",
         "cp864", "cp865", "cp866", "cp869", "cp874", "cp1250", "cp1251", "cp1252", "cp1253", "cp1254", "cp1255",
         "cp1256", "cp1257", "cp1258", "iso8859-2", "iso8859-3", "iso8859-4", "iso8859-5", "iso8859-6", "iso8859-7",
         "iso8859-8", "iso8859-9", "iso8859-10", "iso8859-11", "iso8859-13", "iso8859-14", "iso8859-15", "iso8859-16",
         "koi8-r", "koi8-u", "mac-roman", "mac-cyrillic", "mac-greek", "mac-iceland", "mac-latin2", "mac-turkish",
         "cp1006", "cp1125", "cp1140", "cp720", "cp856", "cp500", "cp037", "cp424", "cp875", "cp1026", "cp273", "hp-roman8", "kz1048", "ptcp154", "tis-620"]
out = ["// Code generated by scripts/gen_sbcs.py; DO NOT EDIT.", "", "package runtime", "", "var sbcsTables = map[string]string{"]
canon = {}
for n in names:
    try:
        c = codecs.lookup(n)
    except LookupError:
        continue
    cn = c.name
    chars = []
    for b in range(256):
        try:
            chars.append(bytes([b]).decode(n))
        except UnicodeDecodeError:
            chars.append("￾")
    s_ = "".join(chars)
    out.append("\t%s: %s," % (json.dumps(cn), json.dumps(s_, ensure_ascii=True)))
    canon[cn] = cn
    for k, v in al.aliases.items():
        if v.replace("_", "-") == cn or v == cn.replace("-", "_"):
            canon[k.replace("_", "-")] = cn
    canon[n] = cn
out.append("}")
out.append("")
out.append("var sbcsAliases = map[string]string{")
for k in sorted(canon):
    out.append('\t"%s": "%s",' % (k, canon[k]))
out.append("}")
open("runtime/sbcs_tables.go", "w").write("\n".join(out) + "\n")
print(len(canon))
